/**
 * 幂等写入预设 skills：
 * - 表为空时直接插入；
 * - 表中全是预设（无用户自建 skill）时清空后重插，保证预设内容升级后能生效；
 * - 存在用户自建 skill（is_preset=0）时不重置，避免覆盖用户数据。
 */
export function seedPresetSkills(): number {
  const db = getDb()
  const rows = db.prepare('SELECT is_preset FROM writing_skills').all() as { is_preset: number }[]
  if (rows.length > 0 && rows.some((r) => r.is_preset === 0)) return 0
  const now = new Date().toISOString()
  const insert = db.prepare(
    'INSERT INTO writing_skills (id, name, category, tags, content, is_preset, created_at, updated_at) VALUES (?, ?, ?, ?, ?, 1, ?, ?)'
  )
  const tx = db.transaction((list: SkillInput[]) => {
    if (rows.length > 0) db.prepare('DELETE FROM writing_skills').run()
    for (const s of list) {
      insert.run(crypto.randomUUID(), s.name, s.category, JSON.stringify(s.tags), s.content, now, now)
    }
  })
  tx(PRESET_SKILLS)
  return PRESET_SKILLS.length
}
