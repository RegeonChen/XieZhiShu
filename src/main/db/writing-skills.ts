import type { WritingSkill } from '../../shared/types'
import { getDb } from './connection'

interface SkillRow {
  id: string
  name: string
  category: 'general' | 'section'
  tags: string
  content: string
  is_preset: number
  created_at: string
  updated_at: string
}

function parseTags(raw: string): string[] {
  try {
    const v = JSON.parse(raw) as unknown
    return Array.isArray(v) ? v.filter((x): x is string => typeof x === 'string') : []
  } catch {
    return []
  }
}

function rowToSkill(row: SkillRow): WritingSkill {
  return {
    id: row.id,
    name: row.name,
    category: row.category,
    tags: parseTags(row.tags),
    content: row.content,
    isPreset: row.is_preset === 1,
    createdAt: row.created_at,
    updatedAt: row.updated_at
  }
}

export function listSkills(): WritingSkill[] {
  const db = getDb()
  const rows = db.prepare('SELECT * FROM writing_skills ORDER BY category, created_at ASC').all() as SkillRow[]
  return rows.map(rowToSkill)
}

export function getSkillById(id: string): WritingSkill | null {
  const db = getDb()
  const row = db.prepare('SELECT * FROM writing_skills WHERE id = ?').get(id) as SkillRow | undefined
  return row ? rowToSkill(row) : null
}

export interface SkillInput {
  name: string
  category: 'general' | 'section'
  tags: string[]
  content: string
}

export function createSkill(input: SkillInput): WritingSkill {
  const name = input.name.trim()
  const content = input.content.trim()
  if (!name) throw new Error('规范名称不能为空')
  if (!content) throw new Error('规范内容不能为空')
  const db = getDb()
  const id = crypto.randomUUID()
  const now = new Date().toISOString()
  db.prepare(
    'INSERT INTO writing_skills (id, name, category, tags, content, is_preset, created_at, updated_at) VALUES (?, ?, ?, ?, ?, 0, ?, ?)'
  ).run(id, name, input.category, JSON.stringify(input.tags ?? []), content, now, now)
  return getSkillById(id)!
}

export function updateSkill(id: string, input: SkillInput): WritingSkill | null {
  const db = getDb()
  if (!getSkillById(id)) return null
  const name = input.name.trim()
  const content = input.content.trim()
  if (!name) throw new Error('规范名称不能为空')
  if (!content) throw new Error('规范内容不能为空')
  db.prepare(
    'UPDATE writing_skills SET name = ?, category = ?, tags = ?, content = ?, updated_at = ? WHERE id = ?'
  ).run(name, input.category, JSON.stringify(input.tags ?? []), content, new Date().toISOString(), id)
  return getSkillById(id)
}

export function deleteSkill(id: string): void {
  const db = getDb()
  db.prepare('DELETE FROM writing_skills WHERE id = ?').run(id)
}

export function listGeneralSkills(): WritingSkill[] {
  return listSkills().filter((s) => s.category === 'general')
}

export function listSectionSkills(): WritingSkill[] {
  return listSkills().filter((s) => s.category === 'section')
}

/** 按撰写标题匹配部类细则 skills：标题包含 skill.name 或任一 tag 即命中 */
export function matchSectionSkills(title: string): WritingSkill[] {
  const t = (title ?? '').replace(/\s+/g, '')
  if (!t) return []
  return listSectionSkills().filter((s) => {
    if (s.name && t.includes(s.name.replace(/\s+/g, ''))) return true
    return s.tags.some((tag) => tag && t.includes(tag))
  })
}

